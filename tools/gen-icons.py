# Glyphs the interface asks for by name (`Icon`), not by a lucide name.
EXTRA = ["favorite", "warning", "skull", "person", "bolt", "memory"]


def glyph_path(name: str) -> str:
    svg = (SVG_DIR / f"{name}.svg").read_text(encoding="utf8")
    d = "".join(re.findall(r'<path[^>]* d="([^"]*)"', svg))
    assert d, name
    return d


glyphs = {name: glyph_path(name) for name in sorted(set(COMPONENTS.values()) | set(EXTRA))}

lines = [
    "// Generated by tools/gen-icons.py. Do not edit.",
    "// Glyphs: Material Symbols, Sharp, weight 400 (Apache-2.0, https://github.com/google/material-design-icons).",
    "// Sharp corners suit the HUD; the 960-unit grid is scaled to the box by the viewBox.",
    'import type { SVGProps } from "react";',
    "",
    "const PATHS = {",
]
lines += [f'  "{k}": "{v}",' for k, v in glyphs.items()]
lines += [
    "} as const;",
    "",
    "export type IconName = keyof typeof PATHS;",
    "",
    "type IconProps = Omit<SVGProps<SVGSVGElement>, \"name\">;",
    "",
    "/** A glyph by name. 24px by default; a `size-*` class resizes it. */",
    "export function Icon({ name, ...props }: IconProps & { name: IconName }) {",
    "  return (",
    '    <svg width="24" height="24" viewBox="0 -960 960 960" fill="currentColor" aria-hidden {...props}>',
    "      <path d={PATHS[name]} />",
    "    </svg>",
    "  );",
    "}",
    "",
    "// The names the app used from lucide-react.",
]
for comp, glyph in COMPONENTS.items():
    lines.append(f'export const {comp} = (props: IconProps) => <Icon name="{glyph}" {{...props}} />;')
OUT.write_text("\n".join(lines) + "\n", encoding="utf8")
print(f"{OUT.relative_to(ROOT)}: {len(glyphs)} glyphs, {len(COMPONENTS)} components, {OUT.stat().st_size} bytes")
