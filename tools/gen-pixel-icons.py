# Glyphs the interface asks for by name (`PixelIcon`), not by a lucide name.
EXTRA = ["heart", "warning-diamond", "skull-sharp", "human", "zap", "cpu-sharp"]


def sprite_path(art: str) -> str:
    rows = [r for r in art.strip("\n").split("\n")]
    assert len(rows) == 12 and all(len(r) == 12 for r in rows), "a sprite is 12x12"
    parts = []
    for y, row in enumerate(rows):
        for m in re.finditer(r"#+", row):
            x, w = m.start() * 2, (m.end() - m.start()) * 2
            parts.append(f"M{x} {y * 2}h{w}v2h-{w}z")
    return "".join(parts)


def file_path(name: str) -> str:
    svg = (SVG_DIR / f"{name}.svg").read_text(encoding="utf8")
    d = "".join(re.findall(r'<path[^>]* d="([^"]*)"', svg))
    assert d, name
    return d


glyphs: dict[str, str] = {}
for name in sorted(set(COMPONENTS.values()) | set(EXTRA)):
    glyphs[name] = sprite_path(SPRITES[name]) if name in SPRITES else file_path(name)

