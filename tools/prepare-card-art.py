"""Slices tools/art/card-board.svg (the Recraft board) into the pieces the character card is built from.

The board is cut into a 3-slice strip (module | stretchable middle | traces) plus a bottom connector strip,
so the card can be any height and the portrait window stays at a fixed scale. Fills become CSS classes
(coloured in src/index.css, `.card-art`), the magenta window is dropped (the portrait sits there) and its
geometry is written to src/assets/card/geometry.ts.

The red frame around the window is thinned: the window grows outward by GROW board units and the portrait
covers the inner part of the frame. The four small corner brackets drawn on the frame go to their own piece
(`brackets.svg`) that the card lays over the portrait.

Usage: python tools/prepare-card-art.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tools/art/card-board.svg"
OUT = ROOT / "src/assets/card"

CLASSES = {
    "#D02C29": "c-mark",
    "#360706": "c-edge",
    "#1E1F23": "c-board",
    "#7E848F": "c-line",
    "#C59D47": "c-gold",
    "#D1AC57": "c-gold",
}
WINDOW = "#FD00F9"
DROP = {"#EDEDEC"}  # the background that leaked into the corners and the connector notches

W, H = 1372, 766
MODULE_X, MID_X = 656, 670  # slice borders along x
BODY_H = 700  # the connector strip starts here
GROW = 17  # how far the portrait window grows over the red frame, board units

svg = SRC.read_text(encoding="utf8")
transform = re.search(r'transform="([^"]*)"', svg).group(1)
m = re.match(r"matrix\(([^ ]+) 0 0 ([^ ]+) ([^ ]+) ([^)]+)\)", transform)
sx, sy, tx, ty = (float(v) for v in m.groups())

paths = []  # (fill, d, bbox)
window = None
for attrs in re.findall(r"<path ([^>]*?)/>", svg):
    fill = re.search(r'fill="([^"]*)"', attrs).group(1).upper()
    d = re.search(r' d="([^"]*)"', attrs).group(1)
    nums = [float(v) for v in re.findall(r"-?\d+\.?\d*", d)]
    xs = [x * sx + tx for x in nums[0::2]]
    ys = [y * sy + ty for y in nums[1::2]]
    bbox = (min(xs), min(ys), max(xs), max(ys))
    if fill == WINDOW:
        window = bbox
    elif fill in CLASSES:
        paths.append((fill, d, bbox))
    elif fill not in DROP:
        raise SystemExit(f"unmapped fill {fill}")
assert window, "no magenta window in the board"
wx0, wy0, wx1, wy1 = window


def is_bracket(fill: str, bbox: tuple) -> bool:
    """A grey corner bracket lying on the frame: its centre is next to a corner of the window."""
    if fill != "#7E848F":
        return False
    cx, cy = (bbox[0] + bbox[2]) / 2, (bbox[1] + bbox[3]) / 2
    corners = [(wx0, wy0), (wx1, wy0), (wx0, wy1), (wx1, wy1)]
    return any(abs(cx - x) < 25 and abs(cy - y) < 25 for x, y in corners)


def piece(name: str, x0: float, y0: float, x1: float, y1: float, aspect: str, brackets: bool = False) -> None:
    body = "".join(
        f'<path class="{"c-bracket" if brackets else CLASSES[f]}" d="{d}"/>'
        for f, d, b in paths
        if b[0] < x1 and b[2] > x0 and b[1] < y1 and b[3] > y0
        and (is_bracket(f, b) == brackets if name in ("module", "brackets") else True)
    )
    (OUT / f"{name}.svg").write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{x0:g} {y0:g} {x1 - x0:g} {y1 - y0:g}" '
        f'preserveAspectRatio="{aspect}"><g transform="{transform}">{body}</g></svg>',
        encoding="utf8",
    )


OUT.mkdir(parents=True, exist_ok=True)
piece("module", 0, 0, MODULE_X, BODY_H, "xMinYMin meet")
piece("brackets", 0, 0, MODULE_X, BODY_H, "xMinYMin meet", brackets=True)
piece("middle", MODULE_X, 0, MID_X, BODY_H, "none")
piece("traces", MID_X, 0, W, BODY_H, "xMaxYMin meet")
piece("connector", 0, BODY_H, W, H, "none")

# The octagon's cuts are 48.5 units (measured); offsetting the edges outward by GROW lengthens each cut by GROW * (2 - sqrt 2).
chamfer = 48.5 * sx + GROW * (2 - 2**0.5)
wx0, wy0, wx1, wy1 = wx0 - GROW, wy0 - GROW, wx1 + GROW, wy1 + GROW
pct = lambda v, total: f"{v / total * 100:.3f}%"
(OUT / "geometry.ts").write_text(
    "// Generated by tools/prepare-card-art.py. Do not edit.\n"
    f"export const CARD_ART = {{\n"
    f"  /** Slice widths and the body height, in board units. */\n"
    f"  moduleW: {MODULE_X},\n  middleW: {MID_X - MODULE_X},\n  tracesW: {W - MID_X},\n  bodyH: {BODY_H},\n  connectorH: {H - BODY_H},\n"
    f"  /** The portrait window inside the module slice, as shares of it. */\n"
    f'  window: {{ left: "{pct(wx0, MODULE_X)}", top: "{pct(wy0, BODY_H)}", width: "{pct(wx1 - wx0, MODULE_X)}", height: "{pct(wy1 - wy0, BODY_H)}", '
    f'cutX: "{pct(chamfer, wx1 - wx0)}", cutY: "{pct(chamfer, wy1 - wy0)}" }},\n'
    f"}} as const;\n",
    encoding="utf8",
)
for f in sorted(OUT.iterdir()):
    print(f.name, f.stat().st_size)
